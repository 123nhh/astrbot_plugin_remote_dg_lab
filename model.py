class CustomPulseData:
    """自定义波形，默认包含 DG-Lab App 内置波形"""

    def __init__(self):
        self.data: Dict[str, List[PulseOperation]] = dict(DEFAULT_PULSE_DATA)

    @property
    def keys(self) -> list:
        return list(self.data.keys())

    def get(self, name: str):
        return self.data.get(name)

    def __bool__(self):
        return bool(self.data)


